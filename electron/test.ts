import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {Ledger,businessTime} from './database';
import {ScannerEngine} from './engine';
import {HALF_PRICE_BARCODE,type EngineEvent} from './types';
const root=path.resolve('.cache/tests');fs.mkdirSync(root,{recursive:true});const file=path.join(root,`ledger-${process.pid}.sqlite3`);const ledger=new Ledger(file);let now=Date.parse('2026-10-18T15:00:00.000Z');const events:EngineEvent[]=[];const engine=new ScannerEngine(ledger,e=>events.push(e),()=>now);
async function test(){
 assert.equal(ledger.products().length,47);assert.equal(ledger.db.pragma('journal_mode',{simple:true}),'wal');assert.equal(ledger.db.pragma('foreign_keys',{simple:true}),1);
 assert.equal(ledger.db.pragma('synchronous',{simple:true}),2);
 const result=engine.dualFire();assert.equal(result.passed,true);assert.equal(ledger.today(new Date(now)).summary.revenue,1150);
 const rows=result.ids.map(id=>ledger.get(id));assert.equal(rows[0].created_at,rows[1].created_at);assert.equal(rows.find(t=>t.scanner_id==='SCANNER_1')?.quantity,5);assert.equal(engine.states.SCANNER_1.multiplier,1);
 engine.scan('SCANNER_1',' x2 ');engine.scan('SCANNER_1','mod-waste');engine.scan('SCANNER_2','X3');const waste=engine.scan('SCANNER_1','B001')!;assert.equal(waste.quantity,2);assert.equal(waste.tx_type,'WASTE');assert.equal(waste.subtotal_cents,0);assert.equal(waste.item_value_cents,400);assert.equal(engine.states.SCANNER_2.multiplier,3);
 engine.scan('SCANNER_2','ACT-RESET');const regularSale=engine.scan('KEYBOARD','D001')!;const refund=engine.refundSale(regularSale.id,regularSale.tx_uid,1,'KEYBOARD');assert.equal(refund.subtotal_cents,-300);
 engine.scan('KEYBOARD','MOD-GIFT');const gift=engine.scan('KEYBOARD','D006')!;assert.equal(gift.item_value_cents,200);assert.equal(gift.subtotal_cents,0);
 engine.scan('SCANNER_1','MUL-05');engine.scan('SCANNER_1','BAD');assert.equal(events.at(-1)?.code,'ERROR_UNKNOWN_SKU');assert.equal(engine.states.SCANNER_1.multiplier,5);now+=5001;const expired=engine.scan('SCANNER_1','B002')!;assert.equal(expired.quantity,1);
 assert.throws(()=>ledger.db.prepare('DELETE FROM transactions WHERE id=?').run(expired.id),/cannot be deleted/);
 assert.throws(()=>ledger.db.prepare('UPDATE transactions SET quantity=2 WHERE id=?').run(expired.id),/one-way void/);
 const own=engine.scan('SCANNER_2','ACT-UNDO')!;assert.equal(own.scanner_id,'SCANNER_2');assert.equal(own.is_voided,1);assert.throws(()=>ledger.db.prepare('UPDATE transactions SET is_voided=0,voided_at=NULL WHERE id=?').run(own.id),/one-way void/);
 const sameTick=engine.scan('SCANNER_1','B003')!;
 now+=60_000;
 assert.equal(engine.scan('SCANNER_1','ACT-UNDO')?.id,sameTick.id);
 now+=1;
 const otherScanner=engine.scan('SCANNER_2','S001')!;
 assert.equal(engine.scan('SCANNER_1','ACT-UNDO'),undefined);
 assert.equal(events.at(-1)?.code,'UNDO_NOT_FOUND');
 assert.equal(ledger.get(expired.id).is_voided,0);
 assert.equal(ledger.get(otherScanner.id).is_voided,0);
 const unidentified=engine.scan('KEYBOARD','B001')!;
 assert.equal(engine.scan('KEYBOARD','act-undo'),undefined);
 assert.equal(events.at(-1)?.code,'UNDO_SCANNER_UNAVAILABLE');
 assert.equal(ledger.get(unidentified.id).is_voided,0);
 assert.equal(ledger.get(otherScanner.id).is_voided,0);
 assert.throws(()=>engine.manualUndo(gift.id,expired.tx_uid),/已发生变化/);
 assert.equal(ledger.get(gift.id).is_voided,0);
 engine.manualUndo(gift.id,gift.tx_uid);assert.equal(ledger.get(gift.id).is_voided,1);
 const previous=ledger.get(refund.id);ledger.db.prepare('UPDATE products SET price_cents=999 WHERE sku=?').run('D001');assert.equal(ledger.get(refund.id).unit_price_cents_snapshot,previous.unit_price_cents_snapshot);
 ledger.db.prepare('UPDATE products SET is_active=0 WHERE sku=?').run('D002');engine.scan('SCANNER_1','D002');assert.equal(events.at(-1)?.code,'ERROR_UNKNOWN_SKU');assert.throws(()=>engine.scan('BOGUS' as never,'B001'));
 assert.deepEqual(businessTime(new Date('2025-12-31T15:59:59Z')),{date:'2025-12-31',hour:23});assert.deepEqual(businessTime(new Date('2026-07-01T16:00:00Z')),{date:'2026-07-02',hour:0});
 const before=ledger.today(new Date(now)).summary.transactions;for(let i=0;i<250;i++)assert.equal(engine.dualFire().passed,true);assert.equal(ledger.today(new Date(now)).summary.transactions,before+500);
 ledger.db.prepare("UPDATE products SET price_cents=201 WHERE sku='B001'").run();
 const beforeHalfPrice=ledger.today(new Date(now)).summary;
 engine.scan('SCANNER_1',HALF_PRICE_BARCODE);
 engine.scan('SCANNER_1','MUL-03');
 assert.equal(engine.scan('SCANNER_2','B001')?.subtotal_cents,201);
 const halfPrice=engine.scan('SCANNER_1','B001')!;
 assert.equal(halfPrice.tx_type,'SALE');
 assert.equal(halfPrice.half_price,1);
 assert.equal(halfPrice.quantity,3);
 assert.equal(halfPrice.unit_price_cents_snapshot,101);
 assert.equal(halfPrice.subtotal_cents,303);
 assert.equal(engine.scan('SCANNER_1','B001')?.subtotal_cents,201);
 engine.scan('SCANNER_1','MOD-REFUND');
 engine.scan('SCANNER_1',HALF_PRICE_BARCODE);
 ledger.setProductActive(halfPrice.product_id,false);
 ledger.db.prepare("UPDATE products SET price_cents=301 WHERE sku='B001'").run();
 assert.equal(engine.scan('SCANNER_1','B001'),undefined);
 const [request]=engine.snapshot().pendingRefunds;
 assert.deepEqual(request,{id:1,date:halfPrice.business_date,sku:'B001',quantity:1,scannerId:'SCANNER_1',halfOnly:true});
 const search={date:halfPrice.business_date,query:'B001',halfOnly:true,page:0};
 assert.equal(ledger.findRefundSales(search).rows[0].tx_uid,halfPrice.tx_uid);
 assert.throws(()=>engine.confirmRefund(request.id,halfPrice.id,'previous-ledger',1),/已变更/);
 assert.equal(engine.pendingRefundCount,1);
 const halfRefund=engine.confirmRefund(request.id,halfPrice.id,halfPrice.tx_uid,1);
 assert.throws(()=>engine.confirmRefund(request.id,halfPrice.id,halfPrice.tx_uid,1),/已经处理或失效/);
 assert.equal(halfRefund.refund_of,halfPrice.id);
 assert.equal(ledger.findRefundSales(search).rows[0].refundable,2);
 assert.throws(()=>engine.refundSale(halfPrice.id,halfPrice.tx_uid,3,'SCANNER_1'),/超过/);
 assert.throws(()=>engine.refundSale(halfPrice.id,'previous-ledger',1,'SCANNER_1'),/已变更/);
 assert.equal(halfRefund.tx_type,'REFUND');
 assert.equal(halfRefund.half_price,1);
 assert.equal(halfRefund.subtotal_cents,-101);
 assert.equal(ledger.today(new Date(now)).summary.revenue,beforeHalfPrice.revenue+604);
 assert.equal(ledger.today(new Date(now)).summary.items,beforeHalfPrice.items+4);
 assert.throws(()=>ledger.db.prepare("UPDATE transactions SET is_voided=1,voided_at=?,half_price=0 WHERE id=?").run(new Date(now).toISOString(),halfPrice.id),/one-way void/);
 assert.throws(()=>engine.manualUndo(halfPrice.id,halfPrice.tx_uid),/先撤销对应的退款/);
 engine.manualUndo(halfRefund.id,halfRefund.tx_uid);
 assert.equal(ledger.findRefundSales(search).rows[0].refundable,3);
 engine.manualUndo(halfPrice.id,halfPrice.tx_uid);
 assert.equal(ledger.today(new Date(now)).summary.revenue,beforeHalfPrice.revenue+402);
 engine.openRefund();
 const [manualRequest]=engine.snapshot().pendingRefunds;
 engine.dismissRefund(manualRequest.id);
 assert.equal(engine.pendingRefundCount,0);
 ledger.setProductActive(halfPrice.product_id,true);
 engine.scan('SCANNER_1',HALF_PRICE_BARCODE);engine.scan('SCANNER_1','ACT-RESET');
 assert.equal(engine.states.SCANNER_1.halfPrice,false);
 engine.scan('SCANNER_1',HALF_PRICE_BARCODE);now+=5000;
 assert.equal(engine.scan('SCANNER_1','B001')?.half_price,0);
 engine.scan('KEYBOARD','X10');await new Promise(resolve=>setTimeout(resolve,5100));assert.equal(engine.states.KEYBOARD.multiplier,1);assert.match(events.at(-1)!.message,/已过期/);
 engine.close();ledger.close();const reopened=new Ledger(file);assert.equal(reopened.products().length,47);assert.equal(reopened.get(refund.id).subtotal_cents,-300);assert.equal(reopened.get(halfPrice.id).half_price,1);reopened.close();console.log('PASS: WAL, seeds, same-tick isolation, 500-sale stress, modes and half-price, unknown/inactive, immutable snapshots, one-way void, same-scanner undo and 60-second boundary, Taipei dates, expiry event, persistence.');
}
test().catch(error=>{console.error(error);process.exitCode=1;}).finally(()=>{engine.close();if(ledger.db.open)ledger.close();for(const suffix of ['','-wal','-shm'])fs.rmSync(file+suffix,{force:true});});
